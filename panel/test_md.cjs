// Приёмка отрисовщика markdown. Пишется НЕ той моделью, что пишет код.
//
// Поводом стал экран: владелец открыл «подробности» записи знания и увидел
// сырой файл — решётки заголовков, «птички» цитат, разрывы посреди предложения
// и служебный `END_OF_FILE`. Отрисовщик умел жирный, `код` и списки: его писали
// для однострочных описаний карточек, а скормили ему целый документ.
//
// Панель существует ровно для того, чтобы владелец НЕ ЧИТАЛ markdown. Значит
// разметка на экране — это отказ, а не мелочь, и проверяется он здесь.
//
//     node panel/test_md.cjs
"use strict";
const fs = require("fs");
const path = require("path");

// md.js кладёт функцию в window — даём ему окно и забираем обратно.
const window = {};
const code = fs.readFileSync(path.join(__dirname, "app", "md.js"), "utf8");
new Function("window", code)(window);
const md = window.mdToHtml;

let fails = 0;
function check(ok, msg) {
  console.log((ok ? "OK   " : "FAIL ") + msg);
  if (!ok) fails += 1;
}

// Всё, что реально встречается в знаниях: замерено 2026-08-09 —
// `##` 26 строк, списки 24, `#` 15, таблицы 11, цитаты 8, нумерованные 4.
const DOC = [
  "# Заголовок записи",
  "",
  "## Правило его словами",
  "",
  "> когда игроки не поднимают лут, он как бы и звуков не должен издавать. То есть он",
  "> условно неактивный",
  "",
  "Лежащий лут — не живое тело: он не давит на пол, не сообщает о касаниях и",
  "сдвинуть его нельзя.",
  "",
  "| Слой | Что там |",
  "|---|---|",
  "| Правила | обычный код |",
  "",
  "- первый пункт",
  "- второй пункт",
  "",
  "1. раз",
  "2. два",
  "",
  "Это **важно**, и вот `код`.",
  "",
  "END_OF_FILE: live/x/knowledge/y.md",
].join("\n");

const html = md(DOC);

// --- Разметки на экране быть не должно ни в каком виде
check(!/(^|>)\s*#{1,4}\s/m.test(html), "решёток заголовков в выводе нет");
check(!/(^|>)\s*&gt;\s/m.test(html), "«птичек» цитат в выводе нет");
check(!html.includes("|---"), "разделителя таблицы в выводе нет");
check(!/(^|>)\s*[-*]\s/m.test(html), "дефисов списка в выводе нет");
check(!html.includes("END_OF_FILE"), "служебного хвоста в выводе нет");

// --- Каждая конструкция превратилась в свой тег
check(/<h[23]>/.test(html), "заголовки стали тегами");
check(html.includes("<blockquote>"), "цитата стала цитатой");
check(html.includes("<table>") && html.includes("<td>"), "таблица стала таблицей");
check(html.includes("<ul>") && html.includes("<ol>"), "оба вида списков на месте");
check(html.includes("<strong>важно</strong>"), "жирный работает как прежде");
check(html.includes("<code>код</code>"), "код работает как прежде");

// --- Мягкий перенос — пробел, а не разрыв: файлы свёрстаны по ширине,
//     и <br> на каждой строке рвал предложения посреди слова.
const para = html.match(/<p>Лежащий лут[\s\S]*?<\/p>/);
check(!!para && !para[0].includes("<br>"),
      "строки одного абзаца склеены, а не разорваны <br>");
check(!!para && /касаниях и сдвинуть/.test(para[0]),
      "и склеены пробелом, а не встык");
check(md("строка\n\nдругая").includes("</p>"), "пустая строка по-прежнему делит абзацы");

// --- Безопасность не ослабла: вывод идёт в innerHTML
const evil = md("<script>alert(1)</script> и <img src=x onerror=y>");
check(!evil.includes("<script") && !evil.includes("<img"),
      "чужие теги экранируются, а не исполняются");
check(evil.includes("&lt;script&gt;"), "и видны текстом");
const inQuote = md("> <b>злое</b>");
check(!inQuote.includes("<b>"), "внутри цитаты экранирование тоже работает");
const inCell = md("| a |\n|---|\n| <i>x</i> |");
check(!inCell.includes("<i>"), "и внутри таблицы");

console.log(fails ? `\nНЕ ПРИНЯТО: ${fails} упало` : "\nПРИНЯТО");
process.exit(fails ? 1 : 0);
